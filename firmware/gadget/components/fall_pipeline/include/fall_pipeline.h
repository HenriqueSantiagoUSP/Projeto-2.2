#pragma once

/*
 * Fall detection pipeline of the wearable: the one developed and compared on the PC
 * (modelo/, docs/decisoes.md, 2026-11-11), sample by sample:
 *
 *   200 Hz, 6 axes -> [1] 20 Hz low-pass, one ESP-DSP biquad per axis
 *                  -> [2] trigger: peak of filtered |a| >= L_on, final once 0.5 s
 *                         pass without a higher value
 *                  -> [3] window from -1.0 s to +0.8 s around the peak
 *                  -> [4] 23 time-domain features (fall_features.h)
 *                  -> [5] classifier: random forest (chosen) or logistic regression
 *                  -> [6] fall when P(fall) >= the classifier's threshold
 *
 * The trigger only wakes the classifier; running, sitting down hard or clapping cross
 * L_on too, and the classifier is what tells them from a fall.
 *
 * Coefficients, window sizes and both models come from fall_model.h/.c, GENERATED by
 * modelo/experimentos/09_exportar_vestivel.py from the SisFall at +-8 g: retrain
 * there (e.g. with the wrist data), never edit them here.
 *
 * Plain C over esp_dsp.h and signal_proc, tested on the host against vectors exported
 * from Python (test_host/), except fall_pipeline_classify_timed(), which needs the CPU.
 */

#include <stdbool.h>
#include <stdint.h>

#include "fall_features.h"
#include "fall_model.h"
#include "signal_proc.h"

#define FP_CHANNELS     6   /* ax, ay, az (g), gx, gy, gz (deg/s) */

/* A peak must be final before its window closes, and the next one cannot close first. */
_Static_assert(FALL_MODEL_POST - 1 >= FALL_MODEL_TRIGGER_GAP, "window closes before its peak is final");
_Static_assert(2 * FALL_MODEL_TRIGGER_GAP >= FALL_MODEL_POST, "two windows could be pending at once");

/* ---------------------------------------------------------------------------
 * [2] Trigger (modelo/queda/pipeline.py, gatilho_causal)
 * ------------------------------------------------------------------------- */

typedef struct {
    float    l_on;
    float    prev;          /* previous |a|: a peak starts only on a rise */
    bool     started;
    bool     tracking;
    float    peak;
    uint32_t peak_index;
} fp_trigger_t;

void fp_trigger_init(fp_trigger_t *trigger, float l_on_g);

/*
 * Feeds |a| of sample n. Returns true when the peak being tracked becomes final,
 * FALL_MODEL_TRIGGER_GAP samples after it with nothing higher, with its sample index
 * and value in *peak_index and *peak.
 */
bool fp_trigger_feed(fp_trigger_t *trigger, float a, uint32_t n, uint32_t *peak_index, float *peak);

/* ---------------------------------------------------------------------------
 * [5] Classifier
 * ------------------------------------------------------------------------- */

typedef enum {
    FP_CLASSIFIER_RF,   /* random forest: the chosen model */
    FP_CLASSIFIER_LR,   /* logistic regression: 23 weights, the simplest to audit */
} fp_classifier_t;

/* P(fall) for a feature vector; not calibrated, compare it with the threshold. */
float fp_classifier_prob(fp_classifier_t classifier, const float features[FALL_MODEL_N_FEATURES]);
float fp_classifier_threshold(fp_classifier_t classifier);
const char *fp_classifier_name(fp_classifier_t classifier);

/* ---------------------------------------------------------------------------
 * The whole pipeline
 * ------------------------------------------------------------------------- */

typedef struct {
    uint32_t peak_index;                        /* sample count at the trigger peak */
    float    a_peak;                            /* filtered |a| at the peak, g */
    float    features[FALL_MODEL_N_FEATURES];
    float    prob;                              /* classifier output, 0..1 */
    bool     fall;                              /* prob >= the classifier's threshold */
} fp_result_t;

typedef struct {
    fp_classifier_t classifier;

    /* [1] filter: ESP-DSP order {b0, b1, b2, a1, a2}, one delay line per axis */
    float    coef[5];
    float    delay[FP_CHANNELS][2];
    bool     started;
    uint32_t n;                                 /* samples fed so far */

    /* [2] */
    fp_trigger_t trigger;
    bool     pending;                           /* a final peak whose window is still filling */
    uint32_t pending_index;
    float    pending_a;

    /* [3] the newest FALL_MODEL_WINDOW_LEN filtered samples of each axis */
    sp_ring_t ring[FP_CHANNELS];
    float    ring_storage[FP_CHANNELS][FALL_MODEL_WINDOW_LEN];

    /* the last completed window, one array per axis (ESP-DSP fast path) */
    float    window[FP_CHANNELS][FALL_MODEL_WINDOW_LEN] __attribute__((aligned(16)));
    uint32_t window_peak_index;
    float    window_a_peak;
    fall_features_scratch_t scratch;
} fall_pipeline_t;

/* l_on_g: the trigger (FALL_MODEL_TRIGGER_G is what the models were trained with). */
void fall_pipeline_init(fall_pipeline_t *fp, float l_on_g, fp_classifier_t classifier);

/*
 * Feeds one raw sample: ax, ay, az in g and gx, gy, gz in deg/s. Returns true when the
 * window around a trigger peak has just completed (FALL_MODEL_POST - 1 samples after
 * the peak); it is copied aside, and fall_pipeline_classify() may run any time before
 * the next window completes, at least FALL_MODEL_TRIGGER_GAP samples later.
 */
bool fall_pipeline_feed(fall_pipeline_t *fp, const float sample[FP_CHANNELS]);

/* Features and classifier over the last completed window. */
void fall_pipeline_classify(fall_pipeline_t *fp, fp_result_t *out);

/*
 * Same, and returns the CPU cycles it took, counted inside a critical section so no
 * interrupt or the other core steals cycles from the count (slide pattern). Device only.
 */
uint32_t fall_pipeline_classify_timed(fall_pipeline_t *fp, fp_result_t *out);
